#!/usr/bin/env node
/**
 * Generates the migration that seeds legal_documents / legal_document_versions
 * from the markdown drafts in legal/*.md.
 *
 * legal/*.md is the source an attorney reviews and edits. Hand-transcribing
 * that text a second time into a SQL migration is exactly how the two drift —
 * someone fixes a clause in the markdown, forgets the copy in the migration,
 * and the document a volunteer signs is the stale one. This script makes the
 * migration a build artifact of the markdown instead of a second original.
 *
 * The signature block at the foot of each file ("---" then "**Signature
 * block**" then blank `_______________` fields) is stripped: it is meant for a
 * printed page, and the web wizard collects the same information through real
 * form inputs, not blank lines. The "Draft — not reviewed" notice is kept in
 * on purpose — see the comment in the generated file.
 *
 * Usage:
 *   node scripts/generate-legal-seed.mjs > supabase/migrations/<timestamp>_seed_legal_documents.sql
 */
import { readFileSync } from 'fs';

/** slug, source file, kind, minors_only, sort_order — the document catalogue. */
const DOCS = [
  ['volunteer-application', '01-volunteer-application.md', 'application', false, 10],
  ['volunteer-agreement', '02-volunteer-agreement.md', 'agreement', false, 20],
  ['release-and-waiver', '03-release-and-waiver.md', 'release', false, 30],
  ['media-consent', '04-media-consent.md', 'media_consent', false, 40],
  ['guardian-consent', '05-guardian-consent.md', 'guardian_consent', true, 50],
  ['code-of-conduct', '06-code-of-conduct.md', 'code_of_conduct', false, 60]
];

const TITLES = {
  'volunteer-application': ['Volunteer Application', 'Solicitud de Voluntariado'],
  'volunteer-agreement': ['Volunteer Agreement', 'Acuerdo de Voluntariado'],
  'release-and-waiver': [
    'Release, Waiver of Liability, and Assumption of Risk',
    'Exención de Responsabilidad y Aceptación de Riesgos'
  ],
  'media-consent': ['Photo and Media Consent', 'Consentimiento de Fotografía y Medios'],
  'guardian-consent': [
    'Parent / Guardian Consent for a Volunteer Under 18',
    'Consentimiento de Padre/Tutor para un Voluntario Menor de 18'
  ],
  'code-of-conduct': ['Volunteer Code of Conduct', 'Código de Conducta del Voluntario']
};

/**
 * Strips the printed-page signature block and the top H1 (the wizard renders
 * its own heading).
 *
 * The trailing block is headed "**Signature block**" in five documents but
 * "**Acknowledgement**" in the code of conduct, and absent entirely from
 * 01-volunteer-application.md — that file is a field specification for
 * whoever builds the form, not something a volunteer reads and signs, so it
 * has no such block and must not be cut at all. (An earlier version of this
 * function cut at the LAST "---" divider regardless of what followed it,
 * which for that file meant the one stray "---" near its *top* — truncating
 * the seeded body down to the opening notice and dropping every field.)
 *
 * Matching the heading explicitly, rather than guessing from a bare "---",
 * handles both real headings and correctly does nothing when there is none.
 */
function bodyOnly(markdown) {
  const withoutTitle = markdown.replace(/^#\s+.*\n+/, '');
  const cutMatch = withoutTitle.match(/\n---\n\n\*\*(Signature block|Acknowledgement)\*\*/);
  return (cutMatch ? withoutTitle.slice(0, cutMatch.index) : withoutTitle).trim();
}

/** Postgres dollar-quoting with a tag unlikely to collide with `$$` already inside the text. */
function dollarQuote(text) {
  let tag = 'doc';
  while (text.includes(`$${tag}$`)) tag += '_';
  return `$${tag}$${text}$${tag}$`;
}

const lines = [
  '-- Generated by scripts/generate-legal-seed.mjs from legal/*.md. Do not hand-edit —',
  '-- regenerate instead, or this file and the drafts it came from will drift apart.',
  '--',
  '-- Idempotent: upserts by slug/version, safe to paste into the SQL editor twice.',
  '--',
  '-- The English body still carries "Draft — not for use until reviewed by a',
  '-- Texas-licensed attorney" on purpose. It is the guardrail that stops this',
  '-- from being put in front of a real volunteer or a real parent before that',
  '-- review has happened — see legal/README.md. Remove that sentence from the',
  '-- markdown (and regenerate) only once counsel has signed off.',
  ''
];

for (const [slug, file, kind, minorsOnly, sortOrder] of DOCS) {
  const raw = readFileSync(new URL(`../legal/${file}`, import.meta.url), 'utf8');
  const body = bodyOnly(raw);
  const [titleEn, titleEs] = TITLES[slug];

  lines.push(
    `-- ${'-'.repeat(75)}`,
    `-- ${slug}`,
    `-- ${'-'.repeat(75)}`,
    '',
    'insert into public.legal_documents (slug, title, title_es, kind, required, minors_only, sort_order)',
    `values (${dollarQuote(slug)}, ${dollarQuote(titleEn)}, ${dollarQuote(titleEs)}, ${dollarQuote(kind)}, true, ${minorsOnly}, ${sortOrder})`,
    'on conflict (slug) do update set',
    '  title = excluded.title, title_es = excluded.title_es, kind = excluded.kind,',
    '  minors_only = excluded.minors_only, sort_order = excluded.sort_order;',
    '',
    'with doc as (',
    `  select id from public.legal_documents where slug = ${dollarQuote(slug)}`,
    ')',
    'insert into public.legal_document_versions (document_id, version, effective_from, body_md, body_md_es, is_current)',
    'select doc.id, \'1.0\', current_date,',
    `  ${dollarQuote(body)},`,
    // The Spanish body is not drafted yet — see legal/README.md item on
    // bilingual review. Placeholder keeps the NOT NULL constraint honest
    // about what has actually been translated rather than leaving it out.
    `  ${dollarQuote('[Spanish translation pending attorney-reviewed English text. Contact ' + '' + 'paowtx@gmail.com for this document in Spanish.]')},`,
    '  true',
    'from doc',
    'on conflict (document_id, version) do update set',
    '  body_md = excluded.body_md, body_md_es = excluded.body_md_es, is_current = true;',
    ''
  );
}

process.stdout.write(lines.join('\n') + '\n');
